android {
  namespace = "com.example"
  compileSdk { version = release(36) { minorApiLevel = 1 } }

  defaultConfig {
    applicationId = "com.aistudio.saatan.kzvhym"
    minSdk = 24
    targetSdk = 36
    versionCode = 1
    versionName = "1.0"

    testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
  }

  // Release signing is materialised from environment variables in CI. When no
  // keystore is available the release variant simply stays unsigned instead of
  // failing the whole build at execution time with a cryptic missing-file
  // error (that also broke `build`, which builds release too).
  val releaseKeystore = file(System.getenv("KEYSTORE_PATH") ?: "${rootDir}/my-upload-key.jks")

  signingConfigs {
    create("release") {
      if (releaseKeystore.exists()) {
        storeFile = releaseKeystore
        storePassword = System.getenv("STORE_PASSWORD")
        keyAlias = "upload"
        keyPassword = System.getenv("KEY_PASSWORD")
      } else {
        logger.lifecycle(
          "Release keystore not found at $releaseKeystore: the release APK will be unsigned."
        )
      }
    }
  }

  buildTypes {
    release {
      isCrunchPngs = false
      isMinifyEnabled = true
      isShrinkResources = true
      proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
      signingConfig = signingConfigs.getByName("release").takeIf { it.storeFile != null }
    }
    debug {
      // No custom signingConfig: Gradle generates and uses the standard
      // debug keystore. The previous `debugConfig` pointed at a
      // `debug.keystore` that does not exist in the repository, so every
      // `assembleDebug` failed.
    }
  }
  compileOptions {
    sourceCompatibility = JavaVersion.VERSION_17
    targetCompatibility = JavaVersion.VERSION_17
  }
  buildFeatures {
    compose = true
    buildConfig = true
  }
  testOptions { unitTests { isIncludeAndroidResources = true } }
  dependenciesInfo {
    includeInApk = false
    includeInBundle = true
  }
}

ksp {
